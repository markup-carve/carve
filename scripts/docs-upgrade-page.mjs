// Builds the upgrade pages (docs/upgrade-0-2.md and one page per area under docs/upgrade-0-2/), the anchor
// map the theme redirects old `/upgrade-0-2#key` links with, and the construct index of spec/0.2/UPGRADING.md,
// from the upgrade map, the row cells of UPGRADING.md and the section list in docs-upgrade-page.json.
// `--write` updates them; `--check` (the default) fails when one is stale or a U- row has no section.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, lint } from '../docs/.vitepress/engine.js'

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PAGE = 'docs/upgrade-0-2.md'
const AREA_DIR = 'docs/upgrade-0-2'
const ANCHORS = 'docs/.vitepress/theme/upgrade-anchors.json'
const SIDEBAR = 'docs/.vitepress/config.ts'
const GUIDE = 'spec/0.2/UPGRADING.md'
const GUIDE_URL = 'https://github.com/markup-carve/carve/blob/main/spec/0.2/UPGRADING.md'
const PAGE_URL = 'https://markup-carve.github.io/carve/0.2/upgrade-0-2'
const INDEX_START = '<!-- construct-index:start (generated by scripts/docs-upgrade-page.mjs) -->'
const INDEX_END = '<!-- construct-index:end -->'
const CONFIG = 'scripts/docs-upgrade-page.json'
const SPEC_LINK = /\[((?:[^[\]]|\[[^\]]*\])+)\]\((https:\/\/github\.com\/markup-carve\/carve\/blob\/main\/spec\/[^)\s]+)\)/g
const GENERATED = '<!-- Generated by scripts/docs-upgrade-page.mjs from spec/0.2/data/upgrade-map.json, spec/0.2/UPGRADING.md and scripts/docs-upgrade-page.json. Edit those, then run `npm run docs:upgrade:write`. -->'
const KIND_BADGE = { rewrite: 'tip', escape: 'warning', report: 'danger', none: 'info' }

const read = (path, root) => readFileSync(join(root, path), 'utf8')

/** GitHub heading anchors for every heading line of a Markdown file, keyed by line index. */
export function headingAnchors(lines) {
  const seen = new Map()
  const anchors = new Map()
  let fence = null
  lines.forEach((line, index) => {
    const run = /^(`{3,}|~{3,})/.exec(line)
    if (run) {
      if (fence === null) fence = run[1]
      else if (run[1][0] === fence[0] && run[1].length >= fence.length) fence = null
      return
    }
    if (fence !== null) return
    const match = /^(#{1,6}) (.*)$/.exec(line)
    if (!match) return
    const base = match[2].trim().toLowerCase().replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, '').replace(/ /g, '-')
    const count = seen.get(base) ?? 0
    seen.set(base, count + 1)
    anchors.set(index, { level: match[1].length, title: match[2].trim(), anchor: count ? `${base}-${count}` : base })
  })
  return anchors
}

/** Each U- row of the guide's tables: its cells and the heading it sits under. */
export function guideRows(text) {
  const lines = text.split('\n')
  const anchors = headingAnchors(lines)
  const rows = new Map()
  let heading = null
  lines.forEach((line, index) => {
    if (anchors.has(index)) heading = anchors.get(index)
    const match = /^\| (U-\d+) \|(.*)\|\s*$/.exec(line)
    if (!match) return
    const cells = match[2].split(/(?<!\\)\|/).map((cell) => cell.trim())
    rows.set(match[1], { cells, heading, line: index + 1 })
  })
  return rows
}

/** Every U- id the guide names anywhere, in order of first mention. */
export function guideIds(text) {
  return [...new Set(text.match(/\bU-\d+\b/g) ?? [])]
}

function sectionOfLine(text, lineNumber) {
  const lines = text.split('\n')
  const anchors = headingAnchors(lines)
  let found = null
  for (const [index, heading] of anchors) if (index < lineNumber) found = heading
  return found
}

// Control, bidi and no-break space characters would be invisible or reorder the page; show their code point.
function visible(source) {
  return source.replace(/[\u0000-\u0008\u000b-\u001f\u007f-\u009f ​-‏‪- ⁦-⁩﻿]/gu,
    (char) => `⟨U+${char.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}⟩`)
}

function fenced(lang, body) {
  const text = visible(body.endsWith('\n') ? body.slice(0, -1) : body)
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length))
  const fence = '`'.repeat(longest + 1)
  return `${fence}${lang}\n${text}\n${fence}`
}

// VitePress compiles page text as a Vue template: `{{` outside a fence needs v-pre.
function vueSafe(markdown) {
  const coded = markdown.replace(/(`+)([^`]*?\{\{[^`]*?)\1/g, (_, ticks, code) => `<code v-pre>${escapeHtml(code)}</code>`)
  return coded.split(/((`+)[^`]*?\2|<code[^>]*>.*?<\/code>)/).map((part, index) => {
    if (index % 3 === 2) return ''
    return index % 3 === 1 ? part : part.replace(/\\?\{\{/g, (open) => `<span v-pre>${open}</span>`)
  }).join('')
}

function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

function codeSpan(text) {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length))
  const ticks = '`'.repeat(longest + 1)
  return longest ? `${ticks} ${text} ${ticks}` : `${ticks}${text}${ticks}`
}

function decode(text) {
  return text.replace(/\\\|/g, '|').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#96;/g, '`').replace(/&amp;/g, '&')
}

// The measured rendering rows quote their source and 0.1 HTML without code spans: "Under C2-…, SRC writes HTML in 0.1."
function describe(cells) {
  const text = visible(cells[0].replace(/\s*\*\*SILENT\*\*\s*/g, ' ').trim())
    .split(/(<code>.*?<\/code>)/)
    .map((part, index) => index % 2 ? part : part.replace(/&#96;((?:(?!&#96;).)+?)&#96;/g, (_, code) => codeSpan(decode(code))))
    .join('')
  const match = /^Under ((?:C2-[A-Z]-\d+(?:,| and |, and |, )?)+), (.+?) writes (.+?) in 0\.1\.(.*)$/.exec(text)
  if (!match || match[2].includes('`') || match[3].includes('`') || /^(a|an|the) /.test(match[2])) return text
  const [source, aside] = match[2].split(/ (?=\()/)
  return `Under ${match[1]}: in 0.1, ${codeSpan(decode(source))}${aside ? ` ${aside}` : ''} writes ${codeSpan(decode(match[3]))}.${match[4]}`
}

const sampleMarker = (kind, reason) => `<!-- carve-sample ${JSON.stringify({ [kind]: reason })} -->`

// The 0.2 side is the upgrade output as `carve fmt` writes it, checked the way docs:samples:check reads it.
// A sample that fmt refuses or that still lints needs a reason in `samples` of the config, usually a ticket.
function upgradedSample(row, reasons, errors) {
  const reason = reasons[row.id]
  let source
  try {
    source = format(row.to)
  } catch (error) {
    if (!reason) errors.push(`${row.id}: carve fmt refuses the upgrade output (${error.message}); give a reason in samples of ${CONFIG}`)
    return `${sampleMarker('skip', reason ?? error.message)}\n${fenced('crv', row.to)}`
  }
  const shown = `${visible(source.endsWith('\n') ? source.slice(0, -1) : source)}\n`
  if (format(shown) !== shown) errors.push(`${row.id}: the shown 0.2 sample is not canonical`)
  const findings = lint(shown).map((entry) => entry.code)
  if (findings.length && !reason) errors.push(`${row.id}: the 0.2 sample lints after carve fmt (${findings.join(', ')}); give a reason in samples of ${CONFIG}`)
  if (!findings.length && reason) errors.push(`${row.id}: the 0.2 sample passes lint; drop its entry from samples of ${CONFIG}`)
  return `${findings.length ? `${sampleMarker('lint', reason)}\n` : ''}${fenced('crv', source)}`
}

function isHtml(text) {
  return /^<[a-z]/.test(text) && text.trimEnd().endsWith('>')
}

// Apply `edit` to the lines outside fenced blocks.
function outsideFences(markdown, edit) {
  let fence = null
  return markdown.split('\n').map((line) => {
    const run = /^(`{3,}|~{3,})/.exec(line)
    if (run) {
      if (fence === null) fence = run[1]
      else if (run[1][0] === fence[0] && run[1].length >= fence.length) fence = null
      return line
    }
    return fence === null ? edit(line) : line
  }).join('\n')
}

// Docs body text links only to docs pages: a spec link keeps its text and moves to the closing paragraph.
function externalize(markdown, links) {
  return outsideFences(markdown, (line) => line.replace(SPEC_LINK, (_, text, url) => {
    if (!links.has(url)) links.set(url, text)
    return text
  }))
}

function specParagraph(links) {
  if (!links.size) return []
  return [`**Specification (external):** ${[...links].map(([url, text]) => `[${text}](${url})`).join('; ')}.`, '']
}

function renderRow(row, cells, heading, reasons, errors, links) {
  const badges = [`<Badge type="${KIND_BADGE[row.kind]}" text="${row.kind}" />`]
  if (row.silent) badges.push('<Badge type="warning" text="silent" />')
  const url = `${GUIDE_URL}#${heading.anchor}`
  if (!links.has(url)) links.set(url, `upgrade guide, ${heading.title.replace(/`/g, '')}`)
  const out = [`**${row.id}** ${badges.join(' ')} ${vueSafe(describe(cells))}`, '']
  if (row.kind === 'report' && cells.length > 2) out.splice(1, 0, `Tool: ${vueSafe(cells.at(-1).replace(/; report$/, ''))}.`)
  const from = row.from.startsWith('(') ? null : row.from
  let right = null
  if (row.to && row.to !== row.from && !row.to.startsWith('(')) right = upgradedSample(row, reasons, errors)
  else if (row.meaning02 && !row.meaning02.startsWith('(')) right = fenced(isHtml(row.meaning02) ? 'html' : 'text', row.meaning02)
  if (from && right) {
    // markdown-it-container closes at any colon run as long as its opener, fences included.
    const colons = ':'.repeat(Math.max(2, ...`${from}\n${right}`.split('\n').map((line) => /^\s*(:*)/.exec(line)[1].length)) + 1)
    out.push(`${colons} compare no-render`, fenced('text', from), right, colons, '')
  }
  else if (from) out.push(fenced('text', from), '')
  return out.join('\n')
}

const frontmatter = (description) => ['---', `description: ${JSON.stringify(description)}`, '---', '', GENERATED, '']

/** The area pages in config order: each groups the sections that name it as `page` (default: the section key). */
function areaPages(config) {
  const pages = new Map()
  for (const section of config.sections) {
    const slug = section.page ?? section.key
    const page = pages.get(slug) ?? { slug, sections: [], ...(config.pages?.[slug] ?? {}) }
    page.sections.push(section)
    pages.set(slug, page)
  }
  for (const page of pages.values()) {
    page.title ??= page.sections[0].title
    page.summary ??= page.sections[0].summary
  }
  return [...pages.values()]
}

export function build(root = repo) {
  const config = JSON.parse(read(CONFIG, root))
  const map = JSON.parse(read('spec/0.2/data/upgrade-map.json', root))
  const current = read(GUIDE, root)
  // Anchors depend only on headings, and the index adds exactly one: read rows from the guide with a stub index.
  const guideText = withIndex(current, `${INDEX_START}\n## Index by construct\n${INDEX_END}`)
  const rows = guideRows(guideText)
  const byId = new Map(map.source.map((row) => [row.id, row]))
  const errors = []
  const placed = new Map()
  for (const section of config.sections) {
    if (!section.summary && !config.pages?.[section.page ?? section.key]?.summary) errors.push(`section ${section.key} has no summary in ${CONFIG}`)
    for (const id of section.rows ?? []) {
      if (placed.has(id)) errors.push(`${id} is in sections ${placed.get(id)} and ${section.key}`)
      placed.set(id, section.key)
      if (!byId.has(id)) errors.push(`${id} in section ${section.key} is not a row of the upgrade map`)
      if (!rows.has(id)) errors.push(`${id} in section ${section.key} has no table row in ${GUIDE}`)
    }
  }
  for (const id of byId.keys()) if (!placed.has(id)) errors.push(`${id} of the upgrade map is in no section of ${CONFIG}`)
  for (const id of Object.keys(config.samples ?? {})) if (!byId.has(id)) errors.push(`${id} in samples of ${CONFIG} is not a row of the upgrade map`)
  const withdrawn = guideIds(guideText).filter((id) => !byId.has(id)).sort()

  const areas = areaPages(config)
  const withdrawnPage = { slug: 'withdrawn', title: 'Withdrawn rows', ...(config.pages?.withdrawn ?? {}) }
  // Old anchors of the one-page guide: a section key on its own page lands on the page, a grouped one on its heading.
  const anchors = {}
  for (const page of areas) {
    for (const section of page.sections) anchors[section.key] = page.sections.length > 1 ? `${page.slug}#${section.key}` : page.slug
  }
  anchors.withdrawn = withdrawnPage.slug
  const files = new Map()

  const indexLinks = new Map()
  const toAreas = (markdown) => outsideFences(markdown, (line) => line.replace(/\]\(#([a-z0-9-]+)\)/g, (link, key) => anchors[key] ? `](./upgrade-0-2/${anchors[key]})` : link))
  const index = [
    '---',
    'description: Every change from Carve 0.1 to 0.2, by construct, with the 0.1 and 0.2 source side by side.',
    '---',
    '',
    GENERATED,
    '',
    '# Upgrading from 0.1',
    '',
    externalize(toAreas(config.intro), indexLinks),
    '',
    externalize(toAreas(config.howTo), indexLinks),
    '',
    '## Reading this page {#reading}',
    '',
    externalize(toAreas(config.legend), indexLinks),
    '',
    '## Changes by area {#areas}',
    '',
    '| Area | What changed |',
    '|---|---|',
    ...[...areas, withdrawnPage].map((page) => `| [${page.title}](./upgrade-0-2/${page.slug}) | ${vueSafe(page.summary ?? '').replace(/\|/g, '\\|')} |`),
    '',
  ]
  index.push(...specParagraph(indexLinks))
  files.set(PAGE, index.join('\n'))

  const indexLines = [INDEX_START, '## Index by construct', '', `Each construct links to its page of the [upgrade pages](${PAGE_URL}), which show every row with its 0.1 and 0.2 source, and to the sections of this guide that hold its rows. Rows withdrawn since their ruling are listed on [their own page](${PAGE_URL}/${withdrawnPage.slug}).`, '']
  for (const page of areas) {
    const links = new Map()
    const grouped = page.sections.length > 1
    const out = frontmatter(`Upgrading from 0.1: ${(page.summary ?? page.title).replace(/`/g, '')}`)
    if (grouped) out.push(`# ${page.title}`, '')
    for (const section of page.sections) {
      const body = []
      body.push(`${grouped ? '##' : '#'} ${section.title} {#${section.key}}`, '', vueSafe(section.why), '')
      if (section.note) body.push(section.note, '')
      if (section.body) body.push(section.body, '')
      const ids = [...(section.rows ?? [])].sort()
      for (const id of ids) {
        const guide = rows.get(id)
        if (!byId.has(id) || !guide) continue
        body.push(renderRow(byId.get(id), guide.cells, guide.heading, config.samples ?? {}, errors, links))
      }
      if (section.key === 'ast') {
        body.push('| Row | Change | 0.1 tree | 0.2 tree |', '|---|---|---|---|')
        for (const row of map.tree) body.push(`| ${row.id} | ${row.kind} | ${row.from.replace(/\|/g, '\\|')} | ${row.to.replace(/\|/g, '\\|')} |`)
        body.push('')
      }
      // Area pages sit one directory below the other docs pages.
      out.push(externalize(outsideFences(body.join('\n'), (line) => line.replace(/\]\(\.\//g, '](../')), links))
      const headings = new Map()
      for (const id of ids) {
        const heading = rows.get(id)?.heading
        if (!heading) continue
        const entry = headings.get(heading.anchor) ?? { heading, count: 0 }
        entry.count += 1
        headings.set(heading.anchor, entry)
      }
      const where = [...headings.values()].map(({ heading, count }) => `[${heading.title.replace(/`/g, '')}](#${heading.anchor}) (${count})`)
      const rowsText = ids.length ? `${ids.length} rows: ${where.join(', ')}` : `no source rows; see the section for the ${section.key === 'ast' ? 'tree rows' : 'host changes'}`
      indexLines.push(`- [${section.title}](${PAGE_URL}/${anchors[section.key]}): ${rowsText}.`)
    }
    out.push(...specParagraph(links))
    files.set(`${AREA_DIR}/${page.slug}.md`, out.join('\n'))
  }

  const withdrawnLinks = new Map()
  const withdrawnOut = frontmatter(`Upgrading from 0.1: ${withdrawnPage.summary ?? withdrawnPage.title}`)
  withdrawnOut.push(`# ${withdrawnPage.title} {#withdrawn}`, '', config.withdrawn, '')
  for (const id of withdrawn) {
    const at = guideText.split('\n').findIndex((line) => new RegExp(`\\b${id}\\b[^.]*withdrawn|withdrawn[^.]*\\b${id}\\b|\\b${id}\\b and U-\\d+ (are|were) withdrawn|U-\\d+ and ${id} (are|were) withdrawn`).test(line))
    const heading = at >= 0 ? sectionOfLine(guideText, at) : null
    if (!heading) {
      errors.push(`${id} is named in ${GUIDE} but is neither a map row nor marked withdrawn`)
      continue
    }
    const title = heading.title.replace(/`/g, '')
    const url = `${GUIDE_URL}#${heading.anchor}`
    if (!withdrawnLinks.has(url)) withdrawnLinks.set(url, `upgrade guide, ${title}`)
    withdrawnOut.push(`- ${id}: ${title}`)
  }
  withdrawnOut.push('', ...specParagraph(withdrawnLinks))
  files.set(`${AREA_DIR}/${withdrawnPage.slug}.md`, withdrawnOut.join('\n'))
  files.set(ANCHORS, `${JSON.stringify(anchors, null, 2)}\n`)

  if (existsSync(join(root, AREA_DIR))) {
    for (const name of readdirSync(join(root, AREA_DIR))) {
      if (!files.has(`${AREA_DIR}/${name}`)) errors.push(`${AREA_DIR}/${name} is not an upgrade page; remove it or add its section to ${CONFIG}`)
    }
  }
  // Test fixtures copy only the inputs, so the sidebar check runs only against a checkout that has one.
  if (existsSync(join(root, SIDEBAR))) {
    const sidebar = read(SIDEBAR, root)
    for (const page of [...areas, withdrawnPage]) {
      if (!sidebar.includes(`link: '/upgrade-0-2/${page.slug}'`)) errors.push(`${SIDEBAR} has no sidebar entry for /upgrade-0-2/${page.slug}`)
    }
  }
  indexLines.push('', INDEX_END)
  return { files, guide: withIndex(current, indexLines.join('\n')), errors }
}

export function withIndex(guideText, index) {
  const start = guideText.indexOf(INDEX_START)
  const end = guideText.indexOf(INDEX_END)
  if (start >= 0 && end > start) return guideText.slice(0, start) + index + guideText.slice(end + INDEX_END.length)
  const anchor = guideText.indexOf('\n## ')
  return `${guideText.slice(0, anchor + 1)}${index}\n\n${guideText.slice(anchor + 1)}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { files, guide, errors } = build()
  if (errors.length) {
    console.error(errors.join('\n'))
    process.exit(1)
  }
  const outputs = [...files, [GUIDE, guide]]
  if (process.argv.includes('--write')) {
    mkdirSync(join(repo, AREA_DIR), { recursive: true })
    for (const [path, text] of outputs) writeFileSync(join(repo, path), text)
    console.log(`wrote ${files.size} upgrade files and the construct index of ${GUIDE}`)
  } else {
    const stale = outputs.filter(([path, text]) => !existsSync(join(repo, path)) || read(path, repo) !== text).map(([path]) => path)
    if (stale.length) {
      console.error(`stale: ${stale.join(', ')}; run npm run docs:upgrade:write`)
      process.exit(1)
    }
    console.log('upgrade pages and construct index are current')
  }
}
