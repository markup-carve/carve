#!/usr/bin/env node
/*
 * Derive resources/node-roles.json from resources/ast-schema.json.
 *
 * WHICH FIELDS OF A NODE HOLD OTHER NODES is a fact only the schema knows, and
 * every engine rediscovers it with a generator of its own. The two that exist
 * do not capture the same amount of it: carve-js derives eight tables from this
 * file, including the per-position admitted types and the required-field sets;
 * carve-rs derives four and makes up the difference with rules hand-written in
 * its decoder. markup-carve/carve#2197 is the measurement - regenerating was
 * the entire implementation in one engine and a no-op in the other, for the
 * same schema change.
 *
 * So the table is derived ONCE, here, and published. An engine copies it the
 * way carve-php copies carve-grammars' tiptap map rather than restating it.
 *
 * A position's ROLE is what a generic walker needs and nothing more:
 *
 *   node-sequence    an array of nodes        (`children`, `rows`, `items`)
 *   node-matrix      an array of node arrays  (`line_block.lines`)
 *   single-node      one node                 (`figure.target`)
 *   record-sequence  an array of plain records, which carry no `type` and so
 *                    no position of their own (`table.columns`)
 *
 * A field holding a string, a number or a boolean has no role and is absent:
 * the table answers "where are the nodes", not "what fields exist", which the
 * schema already answers directly.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = resolve(root, 'resources/ast-schema.json')
const outPath = resolve(root, 'resources/node-roles.json')
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))
const defs = schema.$defs

/** The concrete node types a `$ref` or `oneOf` admits, or null for a non-node. */
function membersOf(node) {
  if (node === null || typeof node !== 'object') return null
  if (typeof node.$ref === 'string') {
    const target = defs[node.$ref.replace('#/$defs/', '')]
    if (!target) return null
    const asEnum = target.properties?.type?.enum
    if (Array.isArray(asEnum)) return [...asEnum]
    const asConst = target.properties?.type?.const
    return typeof asConst === 'string' ? [asConst] : null
  }
  // `oneOf` names the blocks a caption can host; `anyOf` names the two entry
  // kinds a definition list interleaves. Both are unions of concrete refs, and
  // reading only one of them silently dropped `definition_list.items` - a
  // position carve-js's own table has, which is what caught it.
  for (const key of ['oneOf', 'anyOf']) {
    if (!Array.isArray(node[key])) continue
    const all = node[key].map(membersOf)
    if (all.some((m) => m === null)) return null
    return [...new Set(all.flat())].sort()
  }
  return null
}

/** A plain record position: an inline object schema with properties and no `type`. */
function isRecord(node) {
  if (node !== null && typeof node === 'object' && typeof node.$ref === 'string') {
    const target = defs[node.$ref.replace('#/$defs/', '')]
    return target !== undefined && isRecord(target)
  }
  return (
    node !== null &&
    typeof node === 'object' &&
    node.type === 'object' &&
    node.properties !== undefined &&
    node.properties.type === undefined
  )
}

const roles = {}
for (const [name, def] of Object.entries(defs)) {
  const owner = def.properties?.type?.const
  if (!owner || !def.properties) continue
  const fields = {}
  for (const [field, value] of Object.entries(def.properties)) {
    if (field === 'type' || field === 'attrs' || field === 'pos') continue
    if (value.type === 'array') {
      const members = membersOf(value.items)
      if (members) fields[field] = { role: 'node-sequence', admits: members }
      else if (isRecord(value.items)) fields[field] = { role: 'record-sequence' }
      else if (value.items?.type === 'array') {
        // An array of node arrays. A walker that only knew `node-sequence`
        // would descend one level and find arrays where it expected nodes, so
        // the nesting is named rather than left to be discovered.
        const inner = membersOf(value.items.items)
        if (inner) fields[field] = { role: 'node-matrix', admits: inner }
      }
      continue
    }
    const members = membersOf(value)
    if (members) fields[field] = { role: 'single-node', admits: members }
  }
  if (Object.keys(fields).length > 0) roles[owner] = fields
}

const out = {
  // Published at this URL by scripts/publish-schema.mjs, which keys off `$id`.
  $id: 'https://markup-carve.github.io/carve/node-roles.json',
  $comment:
    'GENERATED by scripts/generate-node-roles.mjs from resources/ast-schema.json. ' +
    'Do not edit: run `npm run roles:write`. Every position that holds a node or a ' +
    'plain record, keyed by the type that owns it (PART 12 §12(c)).',
  version: 1,
  source: schema.$id,
  roles,
}

const serialized = JSON.stringify(out, null, 2) + '\n'
if (process.argv.includes('--check')) {
  const current = readFileSync(outPath, 'utf8')
  if (current !== serialized) {
    console.error('resources/node-roles.json is stale - run: npm run roles:write')
    process.exit(1)
  }
  console.log(`node-roles.json covers ${Object.keys(roles).length} node types`)
} else {
  writeFileSync(outPath, serialized)
  console.log(`resources/node-roles.json written: ${Object.keys(roles).length} node types`)
}
